import sys
import os
sys.path.insert(0, '/app')
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from datetime import datetime, timezone
from sqlmodel import select
from app.core.database import get_session
from app.models.order import Order

def main():
    session = next(get_session())
    
    # ???????????? ??????????, ?????????????? ???????????? ?? ?????????? ???????? ??????????-???? ????????????????????
    order = session.exec(select(Order).where(Order.iiko_order_id != None).order_by(Order.created_at.desc())).first()
    if not order:
        print("No orders found with iiko_order_id")
        return
        
    print(f"Order ID: {order.id}")
    print(f"External Number: {order.external_number}")
    print(f"Admin Name: {order.admin_name}")
    print(f"Courier Name: {order.courier_name}")
    print(f"Total Amount: {order.total_amount}")
    print(f"Order Type: {order.order_type}")
    
    # ?????????????????? ???? JSON-????????
    print("\nCustomer Info Details keys:")
    if order.customer_info_details:
        print(order.customer_info_details.keys())
        print(order.customer_info_details)
    else:
        print("None")
        
    print("\nOrder Items Details keys:")
    if order.order_items_details:
        # ?????? ?????????? ???????? ???????????? ?????? ??????????????
        if isinstance(order.order_items_details, list):
            print(f"List of {len(order.order_items_details)} items")
            if order.order_items_details:
                print("First item keys:", order.order_items_details[0].keys())
                print("First item sample:", order.order_items_details[0])
        else:
            print(order.order_items_details.keys())
    else:
        print("None")

if __name__ == "__main__":
    main()
